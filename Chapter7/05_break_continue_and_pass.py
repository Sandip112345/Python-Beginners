# break statement in python

for i in range(80):
    if(i==3):
        break
    print(i)


# continue statement in python

for i in range(5):
    if(i==2):
        continue        # skips when i == 2 and continue to 3 i.e. 0, 1, 3, 4 will be printed

    print(i)

# pass statement in python

for i in range(5):
    pass        # will not do anything
